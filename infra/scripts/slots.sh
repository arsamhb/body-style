#!/usr/bin/env bash
# Port-slot registry. Scans <DEV_ROOT>/*/.env for PROJECT_SLOT=N.
#   slots.sh list  DEV_ROOT
#   slots.sh check DEV_ROOT REPO_DIR SLOT
set -euo pipefail

mode=${1:?usage: slots.sh list|check ...}
root=${2:?DEV_ROOT}

# macOS ships bash 3.2, which has no associative arrays. Keep one
# newline-delimited "slot<TAB>name" list and look entries up with grep.
CLAIMS=""
conflict=0
owner_of() { printf '%s\n' "$CLAIMS" | awk -F'\t' -v s="$1" '$1==s {print $2; exit}'; }
scan() {
  local env name slot prev
  for env in "$root"/*/.env; do
    [ -f "$env" ] || continue
    name=$(basename "$(dirname "$env")")
    slot=$(grep -E '^PROJECT_SLOT=' "$env" 2>/dev/null | head -1 | cut -d= -f2 | tr -d '[:space:]"' || true)
    case "$slot" in ''|*[!0-9]*) continue ;; esac
    prev=$(owner_of "$slot")
    if [ -n "$prev" ] && [ "$prev" != "$name" ]; then
      echo "CONFLICT: slot $slot is claimed by both '$prev' and '$name'" >&2
      conflict=1
      continue
    fi
    [ -n "$prev" ] || CLAIMS="$CLAIMS$slot	$name
"
  done
}

case "$mode" in
  list)
    scan
    echo "# Port registry — generated by 'make ports' from $root/*/.env"
    echo "# API 8000+N*100 | web 3000+N*100 (native) 3010+N*100 (compose) | admin +1 | postgres 5433+N | redis 6380+N | mongo 27018+N | minio 9000/9001+N*100"
    echo
    printf '| %-4s | %-24s | %-5s | %-9s | %-11s | %-8s | %-5s | %-5s |\n' Slot Project API 'Web/Adm' 'Compose' Postgres Redis Mongo
    printf '|%s|%s|%s|%s|%s|%s|%s|%s|\n' ------ -------------------------- ------- ----------- ------------- ---------- ------- -------
    printf '%s\n' "$CLAIMS" | grep -v '^$' | sort -n | while IFS='	' read -r n name; do
      printf '| %-4s | %-24s | %-5s | %-9s | %-11s | %-8s | %-5s | %-5s |\n' \
        "$n" "$name" "$((8000+n*100))" "$((3000+n*100))/$((3001+n*100))" \
        "$((3010+n*100))/$((3011+n*100))" "$((5433+n))" "$((6380+n))" "$((27018+n))"
    done
    [ $conflict -eq 0 ] || exit 1
    ;;
  check)
    repo=${3:?REPO_DIR}; slot=${4:?SLOT}
    scan
    me=$(basename "$repo")
    holder=$(owner_of "$slot")
    if [ -n "$holder" ] && [ "$holder" != "$me" ]; then
      echo "CONFLICT: slot $slot belongs to '$holder' (this repo is '$me'). Pick a free slot: make ports" >&2
      exit 1
    fi
    case "$repo" in "$root"/*) ;; *) echo "note: $repo is outside DEV_ROOT=$root, so 'make ports' won't list it" >&2 ;; esac
    [ $conflict -eq 0 ] || exit 1
    ;;
  *) echo "unknown mode $mode" >&2; exit 2 ;;
esac
